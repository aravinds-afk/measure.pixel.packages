// Generates SQL from the TypeScript sources of truth:
//   supabase/migrations/20261023000002_taxonomy.sql  (profession categories + sphere templates)
//   supabase/seed.sql                                 (FICTIONAL demo chapter)
// Run: npm run gen:sql
import { writeFileSync } from "node:fs";
import { CATEGORIES, SPHERES } from "../supabase/functions/_shared/engine/taxonomy.ts";
import { DEMO_CHAPTER, DEMO_MEMBERS, DEMO_REFERRALS } from "../supabase/functions/_shared/demo-data.ts";

const q = (v: unknown): string => {
  if (v == null) return "null";
  if (typeof v === "number" || typeof v === "boolean") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (a: string[]) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : `'{}'::text[]`);

let tax = `-- GENERATED by scripts/generate-sql.ts from engine/taxonomy.ts. Do not edit by hand.\n\n`;
tax += `insert into public.professional_categories (id, name, icon, summary) values\n`;
tax += CATEGORIES.map((c) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.icon)}, ${q(c.summary)})`).join(",\n");
tax += `\non conflict (id) do update set name = excluded.name, icon = excluded.icon, summary = excluded.summary;\n\n`;
for (const s of SPHERES) {
  tax += `insert into public.contact_spheres (chapter_id, template_key, name, description) values (null, ${q(s.id)}, ${q(s.name)}, ${q(s.description)})\n`;
  tax += `  on conflict (template_key) where chapter_id is null do update set name = excluded.name, description = excluded.description;\n`;
  for (const [cat, role] of Object.entries(s.roles)) {
    tax += `insert into public.contact_sphere_categories (sphere_id, category_id, role_description) select id, ${q(cat)}, ${q(role)} from public.contact_spheres where template_key = ${q(s.id)} and chapter_id is null on conflict do nothing;\n`;
  }
}
writeFileSync("supabase/migrations/20261023000002_taxonomy.sql", tax);

let seed = `-- GENERATED by scripts/generate-sql.ts. FICTIONAL DEMO DATA ONLY.\n-- Loads into a chapter flagged is_demo = true. Never import real members into this chapter.\n\nbegin;\n`;
seed += `insert into public.chapters (id, name, region, is_demo) values (${q(DEMO_CHAPTER.id)}, ${q(DEMO_CHAPTER.name)}, ${q(DEMO_CHAPTER.region)}, true) on conflict (id) do nothing;\n`;
for (const m of DEMO_MEMBERS) {
  seed += `insert into public.members (id, chapter_id, external_id, full_name, company, category_id, category_label, business_description, website, company_sizes, service_areas, problems_solved, keywords, icp_description, ideal_referral, field_provenance, source) values (${[
    q(m.id), q(m.chapterId), q(m.externalId), q(m.fullName), q(m.company), q(m.categoryId), q(m.categoryLabel), q(m.businessDescription), q(m.website),
    arr(m.companySizes), arr(m.serviceAreas), arr(m.problemsSolved), arr(m.keywords), q(m.icpDescription), q(m.idealReferral), `${q(JSON.stringify(m.fieldProvenance))}::jsonb`, q("demo_seed"),
  ].join(", ")}) on conflict (id) do nothing;\n`;
  for (const s of m.services) seed += `insert into public.member_services (member_id, name, provenance) values (${q(m.id)}, ${q(s)}, 'verified') on conflict do nothing;\n`;
  for (const s of m.customerSegments) seed += `insert into public.member_icps (member_id, segment, provenance) values (${q(m.id)}, ${q(s)}, 'verified') on conflict do nothing;\n`;
  for (const i of m.industries) {
    seed += `insert into public.industries (name) values (${q(i)}) on conflict do nothing;\n`;
    seed += `insert into public.member_industries (member_id, industry_id, provenance) select ${q(m.id)}, id, 'verified' from public.industries where lower(name) = lower(${q(i)}) on conflict do nothing;\n`;
  }
  if (m.email || m.phone) seed += `insert into public.member_contacts (member_id, email, phone, visibility) values (${q(m.id)}, ${q(m.email)}, ${q(m.phone)}, ${q(m.contactVisibility)}) on conflict do nothing;\n`;
}
for (const m of DEMO_MEMBERS) {
  for (const r of m.relationships) {
    seed += `insert into public.member_relationships (chapter_id, member_id, related_member_id, kind, provenance) values (${q(m.chapterId)}, ${q(m.id)}, ${q(r.memberId)}, ${q(r.kind)}, ${q(r.provenance)}) on conflict do nothing;\n`;
  }
}
for (const r of DEMO_REFERRALS) {
  seed += `insert into public.referral_records (chapter_id, giver_member_id, receiver_member_id, status, description, business_value, consent_confirmed) values (${q(DEMO_CHAPTER.id)}, ${q(r.giverId)}, ${q(r.receiverId)}, ${q(r.status)}, ${q(r.description)}, ${q(r.value)}, true);\n`;
}
seed += `commit;\n`;
writeFileSync("supabase/seed.sql", seed);
console.log("Generated taxonomy migration and seed.sql");
